use std::path::PathBuf;

use objc2::rc::{Retained, autoreleasepool};
use objc2_app_kit::NSPasteboard;
use objc2_foundation::{NSString, NSURL};
use pin_core::Format;

use crate::{Capture, ChangeCount, MAX_CAPTURE_BYTES, Privacy, Result};

const TEXT: &str = "public.utf8-plain-text";
const HTML: &str = "public.html";
const RTF: &str = "public.rtf";
const PNG: &str = "public.png";
const TIFF: &str = "public.tiff";
const JPEG: &str = "public.jpeg";
const HEIC: &str = "public.heic";
const FILE_URL: &str = "public.file-url";
const CONCEALED: &str = "org.nspasteboard.ConcealedType";
const TRANSIENT: &str = "org.nspasteboard.TransientType";
const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";

#[derive(Debug)]
pub struct Clipboard {
    board: Retained<NSPasteboard>,
    limit: usize,
}

impl Clipboard {
    #[expect(
        clippy::unnecessary_wraps,
        reason = "same signature as platforms without clipboard support"
    )]
    pub fn general() -> Result<Self> {
        Ok(Self {
            board: NSPasteboard::generalPasteboard(),
            limit: MAX_CAPTURE_BYTES,
        })
    }

    pub fn change_count(&self) -> ChangeCount {
        ChangeCount(self.board.changeCount())
    }

    pub fn read(&self) -> Capture {
        autoreleasepool(|_| read::read(&self.board, self.limit))
    }

    /// Replaces the clipboard contents. If the OS rejects the write, the previous contents are already cleared.
    pub fn write(&self, formats: &[Format], privacy: Privacy) -> Result<ChangeCount> {
        autoreleasepool(|_| write::write(&self.board, formats, privacy))?;
        Ok(self.change_count())
    }

    /// Empties the clipboard unless something was copied after `count`; returns whether it did.
    pub fn clear_if_unchanged(&self, count: ChangeCount) -> bool {
        if self.change_count() != count {
            return false;
        }
        // NSPasteboard has no atomic check-and-clear; a copy landing in this gap is lost.
        self.board.clearContents();
        true
    }

    #[cfg(test)]
    pub(crate) fn unique() -> Self {
        Self {
            board: NSPasteboard::pasteboardWithUniqueName(),
            limit: MAX_CAPTURE_BYTES,
        }
    }

    #[cfg(test)]
    pub(crate) fn named(other: &Self) -> Self {
        Self {
            board: NSPasteboard::pasteboardWithName(&other.board.name()),
            limit: other.limit,
        }
    }
}

/// Local path of a `file:` URL, including file reference URLs while their file exists.
fn file_path(url: &[u8]) -> Option<PathBuf> {
    let url = NSURL::URLWithString(&NSString::from_str(std::str::from_utf8(url).ok()?))?;
    let path = url.filePathURL()?.path()?;
    Some(PathBuf::from(path.to_string()))
}

